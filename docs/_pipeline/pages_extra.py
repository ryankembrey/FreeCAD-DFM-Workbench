def preferences_page() -> str:
    out = md.header("docs/_pipeline/shots/panels.py, freecad/DFM/gui/preferences.py "
                    "and the other preference pages")
    out += "# Preferences\n\n"
    out += ("The workbench's settings are under **Edit → Preferences → DFM**. Most people never need "
            "to change them: the values each rule checks against are set in the "
            "[Process Library](../guides/process-library.md), not here.\n\n")
    for shot_id, title, _cls in PREFERENCE_PAGES:
        out += f"## {title}\n\n{PREFERENCE_TEXT.get(shot_id, '')}\n\n"
        img = f"../{shot_path(shot_id)}"
        out += f"[![Edit > Preferences > DFM > {title}]({img})]({img})\n\n"
    return out


def features_page() -> str:
    readme = (env.REPO / "freecad/DFM/core/recognition/README.md").read_text(encoding="utf-8")
    m = re.search(r"^## Features and their parameters\n(.*?)^(?:## |### )", readme, re.M | re.S)
    table = m.group(1).strip() if m else ""
    # Keep the table and the paragraphs that explain it.
    out = md.header("freecad/DFM/core/recognition/README.md")
    out += "# Recognized features\n\n"
    out += ("Many rules are about features rather than faces: a boss's wall, a rib's height, a hole's "
            "depth. The workbench finds these features itself with its feature recognition engine, "
            "from the shape alone, and uses the model's history (PartDesign features) as hints when "
            "it has one. See [feature recognition](../concepts/feature-recognition.md) for how it "
            "works.\n\n")
    out += ("This is what it recognizes, the kinds of each, and what it measures on them (in mm and "
            "degrees). The rules use these measurements.\n\n")
    out += table + "\n"
    return out


def write(out, rules, processes) -> None:
    out.write("content/reference/preferences.md", preferences_page())
    out.write("content/reference/features.md", features_page())


# -- changelog ---------------------------------------------------------------------

_SKIP = re.compile(r"^(Bump version|Release version|Merge (pull request|branch))", re.I)


def _git(*args) -> str:
    return subprocess.run(["git", *args], cwd=env.REPO, capture_output=True, text=True,
                          check=True).stdout


def changelog_page() -> str:
    out = ("<!-- Generated by docs/build.py from the git history and its version tags. "
           "Not committed: it is rebuilt on every build. -->\n\n")
    out += "# Changelog\n\n"
    out += "What changed in each version of the workbench, newest first.\n\n"
    try:
        tags = [t for t in _git("tag", "--sort=-v:refname").split() if re.match(r"^v\d", t)]
    except (OSError, subprocess.CalledProcessError):
        tags = []
    if not tags:
        return out + ("The version history isn't available in this build. See the "
                      "[releases on GitHub](https://github.com/ryankembrey/FreeCAD-DFM-Workbench/tags).\n")
    ranges = [("HEAD", tags[0], "Since " + tags[0])]
    ranges += [(tag, tags[i + 1] if i + 1 < len(tags) else None, tag) for i, tag in enumerate(tags)]
    for end, start, title in ranges:
        span = f"{start}..{end}" if start else end
        subjects = [s for s in _git("log", "--format=%s", "--no-merges", span).splitlines()
                    if s.strip() and not _SKIP.match(s)]
        if end == "HEAD":
            if not subjects:
                continue
            out += f"## {title}\n\nNot released yet.\n\n"
        else:
            date = _git("log", "-1", "--format=%cs", end).strip()
            out += f"## {title}\n\n*{date}*\n\n"
        out += "".join(f"- {md.cell(s)}\n" for s in subjects) or "- Version bump only.\n"
        out += "\n"
    return out


def write_changelog() -> None:
    """Write content/changelog.md directly (outside Output). It changes with every
    commit, so it is ignored by git and left out of the up-to-date check."""
    page = env.CONTENT / "changelog.md"
    text = changelog_page()
    if not page.exists() or page.read_text(encoding="utf-8") != text:
        page.write_text(text, encoding="utf-8")
